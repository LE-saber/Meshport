/* Build-time conversion of UI literals only. No translation service at runtime. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const acorn = require('acorn');
const walk = require('acorn-walk');
const glyphs = require('opencc-js').Converter({ from: 'tw', to: 'cn' });
const convert = text => glyphs(text).replace(/装置/g,'设备').replace(/伺服器/g,'服务器').replace(/软体/g,'软件').replace(/使用者/g,'用户').replace(/帐号/g,'账号').replace(/网路/g,'网络').replace(/讯息/g,'消息').replace(/档案/g,'文件').replace(/金钥/g,'密钥');
const root = path.resolve(__dirname, '../..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const write = (p, text) => fs.writeFileSync(path.join(root, p), text);
const ctx = { window: {} }; vm.createContext(ctx);
for (const p of ['theme.js', 'strings.js']) vm.runInContext(read('internal/console/web/' + p), ctx);
const dict = Object.assign(ctx.window.MP_THEME.dict().zh, ctx.window.MP_EXTRA.zh);
const cn = Object.fromEntries(Object.entries(dict).map(([k, v]) => [k, convert(v)]));
cn.langShort = '简中';
write('internal/console/web/zh-CN.js', '/* Generated by scripts/i18n/generate.cjs. */\nwindow.MP_ZH_CN = ' + JSON.stringify(cn, null, 2) + ';\n');
const strings = new Set();
for (const p of ['app.js', 'enrollment.js']) {
  const name = 'internal/agent/web/' + p;
  let src = read(name);
  const edits = [];
  walk.ancestor(acorn.parse(src, { ecmaVersion: 'latest' }), {
    Literal(node, ancestors) {
      if (typeof node.value !== 'string' || !/[\u3400-\u9fff]/u.test(node.value)) return;
      const parent = ancestors.at(-2);
      strings.add(node.value);
      if (parent.type === 'CallExpression' && parent.callee.name === 'mpText') return;
      if (parent.type === 'Property' && parent.key === node) return;
      edits.push({ start: node.start, end: node.end, text: 'mpText(' + src.slice(node.start, node.end) + ')' });
    }
  });
  edits.sort((a,b) => b.start - a.start).forEach(e => { src = src.slice(0,e.start) + e.text + src.slice(e.end); });
  write(name, src);
}
let html = read('internal/agent/web/index.html');
html = html.replace(/<span>([\u3400-\u9fff]+)<\/span>/gu, (_, text) => '<span data-i18n="' + text + '">' + text + '</span>');
for (const m of html.matchAll(/data-i18n="([^"]+)"/g)) strings.add(m[1]);
write('internal/agent/web/index.html', html);
const client = Object.fromEntries([...strings].sort().map(v => [v, convert(v)]));
write('internal/agent/web/zh-CN.js', '/* Generated UI literals; user data is not included. */\nwindow.MP_CLIENT_ZH_CN = ' + JSON.stringify(client,null,2) + ';\n');
const android = read('android/app/src/main/res/values/strings.xml');
fs.mkdirSync(path.join(root,'android/app/src/main/res/values-zh-rCN'), { recursive: true });
write('android/app/src/main/res/values-zh-rCN/strings.xml', android.replace(/>([^<>]+)</g, (_, text) => '>' + convert(text) + '<'));
console.log('Generated console and client Simplified Chinese dictionaries:', Object.keys(cn).length, strings.size);
